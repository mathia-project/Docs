type CustomCollection = Exclude<keyof AppSchema, `directus_${string}`>;
type ListedCollection = keyof typeof schemaFields;
type CollectionItem<Collection extends CustomCollection> = AppSchema[Collection] extends Array<
  infer Item
>
  ? Item
  : never;
type ListedField<Collection extends ListedCollection> = (typeof schemaFields)[Collection][number];
type MissingFields = {
  [Collection in ListedCollection]: Exclude<
    keyof CollectionItem<Collection>,
    ListedField<Collection>
  >;
}[ListedCollection];
type ExtraFields = {
  [Collection in ListedCollection]: Exclude<
    ListedField<Collection>,
    keyof CollectionItem<Collection>
  >;
}[ListedCollection];
type Equal<Left, Right> =
  (<Value>() => Value extends Left ? 1 : 2) extends <Value>() => Value extends Right ? 1 : 2
    ? true
    : false;
type Assert<Condition extends true> = Condition;
type CollectionNamesAreExact = Assert<Equal<CustomCollection, ListedCollection>>;
type FieldNamesAreExact = Assert<Equal<MissingFields | ExtraFields, never>>;

const schemaContractIsExact: CollectionNamesAreExact & FieldNamesAreExact = true;

describe("Directus application schema contract", () => {
  it("covers all 39 PostgreSQL application collections and their exact field names", () => {
    expect(schemaContractIsExact).toBe(true);
    expect(Object.keys(schemaFields)).toHaveLength(39);
  });
});
