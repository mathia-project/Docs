"""Generate an idempotent PostgreSQL seed from the validated CCSS catalog."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Iterable, Sequence


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATA = ROOT / "data" / "standards" / "final" / "ccss_math_grades_6_10.json"
DEFAULT_OUTPUT = ROOT / "postgres" / "migrations" / "202609060002_curriculum_seed.sql"

ITALIAN_COURSE_NAMES = {
    "grade-6": "1ª Media",
    "grade-7": "2ª Media",
    "grade-8": "3ª Media",
    "grade-9": "1ª Superiore",
    "grade-10": "2ª Superiore",
}


def sql_text(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def sql_json(value: Any) -> str:
    encoded = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return f"{sql_text(encoded)}::jsonb"


def sql_bool(value: bool) -> str:
    return "true" if value else "false"


def write_upsert(
    lines: list[str],
    table: str,
    columns: Sequence[str],
    rows: Iterable[Sequence[str]],
    conflict_columns: Sequence[str],
    update_columns: Sequence[str],
    batch_size: int = 100,
) -> None:
    materialized = list(rows)
    for offset in range(0, len(materialized), batch_size):
        batch = materialized[offset : offset + batch_size]
        lines.append(f"INSERT INTO public.{table} ({', '.join(columns)}) VALUES")
        lines.append(",\n".join("    (" + ", ".join(row) + ")" for row in batch))
        lines.append(f"ON CONFLICT ({', '.join(conflict_columns)}) DO UPDATE SET")
        assignments = [f"    {column} = EXCLUDED.{column}" for column in update_columns]
        assignments.append("    updated_at = now()")
        lines.append(",\n".join(assignments) + ";")
        lines.append("")


def generate(document: dict[str, Any]) -> str:
    lines = [
        "-- Generated by postgres/scripts/generate_curriculum_sql.py.",
        "-- Do not edit manually; regenerate it from the validated CCSS JSON.",
        "BEGIN;",
        "",
        "UPDATE public.curriculum_categories SET active = false, updated_at = now();",
        "UPDATE public.curriculum_courses SET active = false, updated_at = now();",
        "UPDATE public.curriculum_domains SET active = false, updated_at = now();",
        "UPDATE public.curriculum_clusters SET active = false, updated_at = now();",
        "UPDATE public.curriculum_standards SET active = false, updated_at = now();",
        "UPDATE public.curriculum_substandards SET active = false, updated_at = now();",
        "DELETE FROM public.curriculum_lookup_aliases;",
        "DELETE FROM public.curriculum_course_substandards;",
        "DELETE FROM public.curriculum_course_standards;",
        "DELETE FROM public.curriculum_course_domains;",
        "",
    ]

    write_upsert(
        lines,
        "curriculum_categories",
        ("id", "code", "name", "active"),
        (
            (sql_text(item_id), sql_text(item["code"]), sql_json(item["name"]), sql_bool(True))
            for item_id, item in document["categories"].items()
        ),
        ("id",),
        ("code", "name", "active"),
    )

    write_upsert(
        lines,
        "curriculum_courses",
        ("id", "grade_level", "name", "spanish_equivalent", "pathway", "source", "active"),
        (
            (
                sql_text(course["id"]),
                str(course["grade"]),
                sql_json({**course["name"], "it": ITALIAN_COURSE_NAMES[course["id"]]}),
                sql_json(course.get("spanishCourseEquivalent")),
                sql_json(course.get("pathway", {})),
                sql_json(course.get("source", {})),
                sql_bool(True),
            )
            for course in document["courses"]
        ),
        ("id",),
        ("grade_level", "name", "spanish_equivalent", "pathway", "source", "active"),
    )

    write_upsert(
        lines,
        "curriculum_domains",
        ("id", "category_id", "code", "name", "category_assignment", "source", "active"),
        (
            (
                sql_text(item_id),
                sql_text(item["categoryId"]),
                sql_text(item["code"]),
                sql_json(item["name"]),
                sql_text(item["categoryAssignment"]),
                sql_json(item.get("source", {})),
                sql_bool(True),
            )
            for item_id, item in document["domains"].items()
        ),
        ("id",),
        ("category_id", "code", "name", "category_assignment", "source", "active"),
    )

    write_upsert(
        lines,
        "curriculum_clusters",
        ("id", "domain_id", "code", "name", "source", "active"),
        (
            (
                sql_text(item_id),
                sql_text(item["domainId"]),
                sql_text(item["code"]),
                sql_json(item["name"]),
                sql_json(item.get("source", {})),
                sql_bool(True),
            )
            for item_id, item in document["clusters"].items()
        ),
        ("id",),
        ("domain_id", "code", "name", "source", "active"),
    )

    write_upsert(
        lines,
        "curriculum_standards",
        ("id", "cluster_id", "code", "ccss_id", "description", "markers", "source", "notes", "active"),
        (
            (
                sql_text(item_id),
                sql_text(item["clusterId"]),
                sql_text(item["code"]),
                sql_text(item["ccssId"]),
                sql_json(item["text"]),
                sql_json(item.get("markers", {})),
                sql_json(item.get("source", {})),
                sql_json(item.get("notes", [])),
                sql_bool(True),
            )
            for item_id, item in document["standards"].items()
        ),
        ("id",),
        ("cluster_id", "code", "ccss_id", "description", "markers", "source", "notes", "active"),
    )

    write_upsert(
        lines,
        "curriculum_substandards",
        ("id", "standard_id", "code", "ccss_id", "description", "markers", "source", "active"),
        (
            (
                sql_text(item_id),
                sql_text(item["standardId"]),
                sql_text(item["code"]),
                sql_text(item["ccssId"]),
                sql_json(item["text"]),
                sql_json(item.get("markers", {})),
                sql_json(item.get("source", {})),
                sql_bool(True),
            )
            for item_id, item in document["substandards"].items()
        ),
        ("id",),
        ("standard_id", "code", "ccss_id", "description", "markers", "source", "active"),
    )

    course_domain_rows: list[tuple[str, ...]] = []
    seen_course_domains: set[tuple[str, str]] = set()
    course_standard_rows: list[tuple[str, ...]] = []
    course_substandard_rows: list[tuple[str, ...]] = []
    for course in document["courses"]:
        for category in course["categories"]:
            for domain in category["domains"]:
                domain_key = (course["id"], domain["domainId"])
                if domain_key not in seen_course_domains:
                    seen_course_domains.add(domain_key)
                    course_domain_rows.append(
                        (sql_text(course["id"]), sql_text(domain["domainId"]))
                    )
                for cluster in domain["clusters"]:
                    for standard in cluster["standards"]:
                        base = (
                            sql_text(course["id"]),
                            sql_text(standard["standardId"]),
                            sql_text(standard["inclusion"]),
                            sql_json(standard.get("coverage", [])),
                        )
                        course_standard_rows.append(base)
                        for substandard_id in standard.get("substandardIds", []):
                            course_substandard_rows.append(
                                (
                                    sql_text(course["id"]),
                                    sql_text(substandard_id),
                                    sql_text(standard["inclusion"]),
                                    sql_json(standard.get("coverage", [])),
                                )
                            )

    write_upsert(
        lines,
        "curriculum_course_domains",
        ("course_id", "domain_id"),
        course_domain_rows,
        ("course_id", "domain_id"),
        (),
    )
    write_upsert(
        lines,
        "curriculum_course_standards",
        ("course_id", "standard_id", "inclusion", "coverage"),
        course_standard_rows,
        ("course_id", "standard_id"),
        ("inclusion", "coverage"),
    )
    write_upsert(
        lines,
        "curriculum_course_substandards",
        ("course_id", "substandard_id", "inclusion", "coverage"),
        course_substandard_rows,
        ("course_id", "substandard_id"),
        ("inclusion", "coverage"),
    )

    alias_rows = []
    for alias, target in document["lookup"].items():
        is_standard = target["kind"] == "standard"
        alias_rows.append(
            (
                sql_text(alias),
                sql_text(target["kind"]),
                sql_text(target["id"]) if is_standard else "NULL",
                "NULL" if is_standard else sql_text(target["id"]),
            )
        )
    write_upsert(
        lines,
        "curriculum_lookup_aliases",
        ("alias", "item_kind", "standard_id", "substandard_id"),
        alias_rows,
        ("alias",),
        ("item_kind", "standard_id", "substandard_id"),
    )

    lines.extend(("COMMIT;", ""))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the checked-in SQL differs from freshly generated output.",
    )
    args = parser.parse_args()

    document = json.loads(args.data.read_text(encoding="utf-8"))
    generated = generate(document)

    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != generated:
            print(f"Generated curriculum SQL is stale: {args.output}")
            return 1
        print(f"Generated curriculum SQL is current: {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Generated curriculum SQL: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
